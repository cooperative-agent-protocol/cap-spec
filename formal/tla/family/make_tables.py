#!/usr/bin/env python
"""LaTeX tables and number macros of the formal results, generated from the model checker's result files
(cap-spec/formal/tla/family/results). Nothing in the paper's verification section is typed by hand.

Writes into formal/tla/family/results/tables/ (or --out):
  r1_formal_macros.tex    \\newcommand numbers (family size, counts of safe schemes, state counts, ...)
  r1_tab_schemes.tex      the five named schemes x properties and assumption ablations (main text)
  r1_tab_elements.tex     how many schemes satisfy safety, by design choice (main text)
  r1_tab_family_full.tex  all 90 schemes (supplement)

  python formal/tla/family/make_tables.py [--m3 formal/tla/family/results/m3_verdicts.txt] [--out <dir>]
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]          # the specification repository
OUT = ROOT / "formal/tla/family/results/tables"
DIMS = ["Arb", "Gate", "Release", "Expiry", "Succession"]
NAMED = ["MutexOnDone", "MutexGroup", "LeaseFenced", "LeaseFencedVacate", "CAP"]
NAMED_TEX = {
    "MutexOnDone": "Mutex, release on completion",
    "MutexGroup": "Mutex group, release on exit",
    "LeaseFenced": "Fenced lease",
    "LeaseFencedVacate": "Fenced lease with vacancy check",
    "CAP": "Proposed protocol",
}
VALUE_TEX = {
    "none": "none", "deny": "deny-on-busy", "queue": "queued", "local": "grant notice", "permit": "timed permit",
    "onDone": "at once", "onVacate": "on vacancy", "ttl": "on silence", "ttlVacate": "on silence, into custody",
    "free": "free", "designated": "designated",
}
OK, NO, NA = r"\checkmark", r"$\times$", "--"


def load(spec: Path, name: str) -> dict[str, dict]:
    p = spec / "formal/tla/family/results" / f"{name}.json"
    return {r["scheme"]: r for r in json.loads(p.read_text())} if p.exists() else {}


def cell(res: dict[str, dict], scheme: str, prop: str, *, with_len: bool = True) -> str:
    r = res.get(scheme)
    if r is None:
        return NA
    if prop in r["holds"]:
        return OK
    if prop in r["fails"]:
        n = len(r["fails"][prop]) - 1          # steps of the shortest counterexample (states - 1)
        return f"{NO}\\,({n})" if with_len and n > 0 else NO
    return NA


def all_hold(res: dict[str, dict], scheme: str, props: list[str]) -> str:
    r = res.get(scheme)
    if r is None:
        return NA
    return OK if all(p in r["holds"] for p in props) else NO


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def num(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=str(ROOT))
    ap.add_argument("--m3", default="", help="verdicts.txt of the three-machine checks (optional)")
    ap.add_argument("--out", default=str(OUT), help="where the tables and macros are written")
    args = ap.parse_args()
    out_dir = Path(args.out)
    spec = Path(args.spec)
    out_dir.mkdir(parents=True, exist_ok=True)

    # base, lossy: the Site's coordinator may give a zone up for its holder (as the implementation does);
    # own, own_l: every release is the holder's own (the environment of this model's first version)
    base, lossy, trivial = load(spec, "base"), load(spec, "lossy"), load(spec, "trivial")
    own, own_l = load(spec, "ownRelease"), load(spec, "ownRelease_lossy")
    g4 = load(spec, "liveG4_safe8")
    abl = {k: load(spec, f"{k}_safe8")
           for k in ("noA2", "noA4", "noA4d", "noA5", "noBoot", "noGrace", "noCustodyLapse")}
    S = ["S1", "S2", "S3"]

    def safe(res: dict[str, dict]) -> list[str]:
        return [s for s, r in res.items() if all(p in r["holds"] for p in S)]

    safe_d, safe_l = safe(base), safe(lossy)
    safe_d_g12 = [s for s in safe_d if all(p in base[s]["holds"] for p in ("G1", "G2"))]
    safe_l_g12 = [s for s in safe_l if all(p in lossy[s]["holds"] for p in ("G1", "G2"))]
    g4_ok = [s for s, r in g4.items() if "G4" in r["holds"]]
    full = [s for s in safe_l_g12 if s in g4_ok]
    safe_l_g4 = [s for s in safe_l if s in g4_ok]
    nontrivial = [s for s, r in trivial.items() if "NotCycle" in r["fails"]]

    macros = [
        "% Generated by formal/tla/family/make_tables.py - do not edit.",
        macro("FamAll", 108), macro("FamSize", len(base)), macro("FamExcluded", 108 - len(base)),
        macro("FamNontrivial", len(nontrivial)),
        macro("FamSafeDurable", len(safe_d)), macro("FamSafeLossy", len(safe_l)),
        macro("FamSafeOwn", len(safe(own))), macro("FamSafeOwnLossy", len(safe(own_l))),
        macro("FamSafeOwnOnly", len([s for s in safe(own) if s not in safe_d])),
        macro("AblNoAFiveGuar", len([s for s, r in abl["noA5"].items()
                                     if all(p in r["holds"] for p in ("G1", "G2"))])),
        macro("FamSafeDurableGuar", len(safe_d_g12)), macro("FamSafeLossyGuar", len(safe_l_g12)),
        macro("FamRecover", len(g4_ok)), macro("FamSafeLossyRecover", len(safe_l_g4)),
        macro("FamFull", len(full)),
        macro("FamMaxStates", num(max(r["states"] for r in list(base.values()) + list(lossy.values())))),
        macro("CapStatesDurable", num(base["CAP"]["states"])), macro("CapStatesLossy", num(lossy["CAP"]["states"])),
    ]
    for k, res in abl.items():
        # a control sequence takes letters only: noA2 -> NoATwo, noA4d -> NoAFourd
        tag = k.replace("no", "No").replace("2", "Two").replace("4", "Four").replace("5", "Five")
        macros.append(macro("Abl" + tag + "Safe", len(safe(res))))
        macros.append(macro("Abl" + tag + "Total", len(res)))
    # which design choices do all safe schemes share?
    for label, names in (("Durable", safe_d), ("Lossy", safe_l)):
        for d in DIMS:
            vals = sorted({base[s][d] for s in names})
            macros.append(f"% safe under {label} restarts: {d} in {vals}")
    # the invariant of the proof for any number of machines, checked on the model (two machines)
    absinv = {k: load(spec, f"{k}_safe8") for k in ("absInv", "absInv_lossy", "absInv_noA5")}
    checked = [(k, s, r) for k, res in absinv.items() for s, r in res.items()]
    if checked:
        macros.append(macro("AbsInvChecked", len(checked)))
        macros.append(macro("AbsInvHold", sum(1 for _, _, r in checked if "AbsInv" in r["holds"])))
        macros.append(macro("AbsInvMaxStates", num(max(r["states"] for _, _, r in checked))))
    m3 = {}
    if args.m3 and Path(args.m3).exists():
        for line in Path(args.m3).read_text().splitlines():
            m = re.match(r"m3_(base|lossy)_(\S+) \| (.*?) \| distinct=([\d,]*) \| (\d+) s", line)
            if m:
                m3[(m.group(1), m.group(2))] = ("No error" in m.group(3), int(m.group(4).replace(",", "") or 0))
        macros.append(macro("MThreeChecked", len(m3)))
        macros.append(macro("MThreeHold", sum(1 for ok, _ in m3.values() if ok)))
        if m3:
            macros.append(macro("MThreeMaxStates", num(max(n for _, n in m3.values()))))
    (out_dir / "r1_formal_macros.tex").write_text("\n".join(macros) + "\n")

    # ---- Table: named schemes x properties
    hdr = ("Scheme & S1 & S2 & S3 & S1--S3 & S1--S3 & G1 & G2 & G4 & no A2 & no A4 & no A5 & no custody rule "
           "\\\\\n"
           " & \\multicolumn{3}{c}{journal kept} & journal lost & own releases & & & & "
           "\\multicolumn{4}{c}{S1--S3} \\\\")
    rows = []
    for s in NAMED:
        rows.append(" & ".join([
            NAMED_TEX[s], cell(base, s, "S1"), cell(base, s, "S2"), cell(base, s, "S3"),
            all_hold(lossy, s, S), all_hold(own, s, S),
            cell(base, s, "G1", with_len=False), cell(base, s, "G2", with_len=False),
            cell(g4, s, "G4", with_len=False),
            all_hold(abl["noA2"], s, S), all_hold(abl["noA4d"], s, S), all_hold(abl["noA5"], s, S),
            all_hold(abl["noCustodyLapse"], s, S)]) + " \\\\")
    (out_dir / "r1_tab_schemes.tex").write_text(
        "% Generated by formal/tla/family/make_tables.py - do not edit.\n"
        "\\begin{tabular}{@{}lcccccccccccc@{}}\n\\toprule\n" + hdr + "\n\\midrule\n" + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n")

    # ---- Table: safe schemes by design choice
    lines = ["% Generated by formal/tla/family/make_tables.py - do not edit.",
             "\\begin{tabular}{@{}llrrrr@{}}", "\\toprule",
             "Design choice & Option & Schemes & Safe, holder's & Safe, journal kept & Safe, journal lost \\\\",
             " & & & releases only & & \\\\", "\\midrule"]
    safe_o = safe(own)
    for d in DIMS:
        tot = Counter(r[d] for r in base.values())
        so = Counter(base[s][d] for s in safe_o)
        sd = Counter(base[s][d] for s in safe_d)
        sl = Counter(base[s][d] for s in safe_l)
        first = True
        for v in sorted(tot, key=lambda v: list(VALUE_TEX).index(v)):
            name = {"Arb": "Arbitration", "Gate": "Entry gate", "Release": "Release", "Expiry": "Expiry",
                    "Succession": "Succession"}[d] if first else ""
            lines.append(f"{name} & {VALUE_TEX[v]} & {tot[v]} & {so.get(v, 0)} & {sd.get(v, 0)} & {sl.get(v, 0)} "
                         "\\\\")
            first = False
        lines.append("\\addlinespace")
    lines[-1] = "\\midrule"
    lines += [f"All & & {len(base)} & {len(safe_o)} & {len(safe_d)} & {len(safe_l)} \\\\", "\\bottomrule",
              "\\end{tabular}"]
    (out_dir / "r1_tab_elements.tex").write_text("\n".join(lines) + "\n")

    # ---- Table: the whole family (supplement)
    lines = ["% Generated by formal/tla/family/make_tables.py - do not edit.",
             "\\begin{longtable}{@{}lllllccccccccr@{}}", "\\toprule",
             "Arbitration & Gate & Release & Expiry & Succession & S1 & S2 & S3 & G1 & G2 & lossy & own & G4 & States "
             "\\\\",
             "\\midrule", "\\endhead"]
    for s, r in sorted(base.items(), key=lambda kv: [list(VALUE_TEX).index(kv[1][d]) for d in DIMS]):
        lines.append(" & ".join([VALUE_TEX[r[d]] for d in DIMS]
                                + [cell(base, s, p) for p in ("S1", "S2", "S3")]
                                + [cell(base, s, p, with_len=False) for p in ("G1", "G2")]
                                + [all_hold(lossy, s, S), all_hold(own, s, S), cell(g4, s, "G4", with_len=False),
                                   num(r["states"])])
                     + " \\\\")
    lines += ["\\bottomrule", "\\end{longtable}"]
    (out_dir / "r1_tab_family_full.tex").write_text("\n".join(lines) + "\n")

    print((out_dir / "r1_formal_macros.tex").read_text())
    print((out_dir / "r1_tab_schemes.tex").read_text())
    print((out_dir / "r1_tab_elements.tex").read_text())
    print("full (S1-S3, G1, G2, G4, lossy):", full)
    print("safe lossy + G4:", safe_l_g4)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
